const STORAGE_KEY = "nexus.lang";
const saved = typeof localStorage !== "undefined" ? localStorage.getItem(STORAGE_KEY) : null;
const initial: Lang = saved === "en" ? "en" : "ar";
function applyLanguage(lang: Lang) {
  document.documentElement.setAttribute("lang", lang);
  document.documentElement.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");
  document.documentElement.classList.toggle("lang-ar", lang === "ar");
  localStorage.setItem(STORAGE_KEY, lang);
}

void i18n.use(initReactI18next).init({
  resources: {
    en: { translation: { ...en, ...enExtra, ...enCommand } },
    ar: { translation: { ...ar, ...arExtra, ...arCommand } }
  },
  lng: initial,
  fallbackLng: "en",
  supportedLngs: ["ar", "en"],
  keySeparator: false,
  nsSeparator: false,
  interpolation: { escapeValue: false },
  returnNull: false
});

applyLanguage(initial);

export function currentLang(): Lang {
  return i18n.language.startsWith("ar") ? "ar" : "en";
}

export async function changeLanguage(lang: Lang): Promise<void> {
  await i18n.changeLanguage(lang);
  applyLanguage(lang);
}

export async function toggleLanguage(): Promise<Lang> {
  const next: Lang = currentLang() === "ar" ? "en" : "ar";
  await changeLanguage(next);
  return next;
}

export { applyLanguage };
export default i18n;
